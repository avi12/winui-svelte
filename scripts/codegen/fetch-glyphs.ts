import { writeFileSync } from "node:fs";
import path from "node:path";

// Fetches, by hand, the icons of Segoe Fluent Icons:
//
//   node scripts/codegen/fetch-glyphs.ts
//
// Reads Microsoft's published list (MicrosoftDocs/windows-dev-docs, CC BY 4.0)
// at the commit pinned below and writes src/components/fluent-glyph.ts, the
// catalogue a FontIcon's `glyph` takes names from. The commit is the one place
// the list's version is named; change it to take a newer list.

const SOURCE_COMMIT = "7ad8a35fd9a697a7caf2af6b751ab1cbd6c48115";
const SOURCE_PATH = "hub/apps/design/iconography/segoe-fluent-icons-font.md";
const SOURCE_URL = `https://raw.githubusercontent.com/MicrosoftDocs/windows-dev-docs/${SOURCE_COMMIT}/${SOURCE_PATH}`;
const OUTPUT_PATH = path.join(import.meta.dirname, "..", "..", "src", "components", "fluent-glyph.ts");
const ROW = /\|\s*:::image[^|]*\|\s*([0-9a-f]{4,5})\s*\|\s*:::no-loc text="([^"]*)":::\s*\|/gi;
const HEXADECIMAL = 16;
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`${SOURCE_URL}: ${response.status}`);
}

const glyphs = new Map<string, number>();
for (const [, code, name] of (await response.text()).matchAll(ROW)) {
  const isRow = code !== undefined && name !== undefined;
  if (!isRow) {
    continue;
  }

  const isRepeated = glyphs.has(name);
  if (isRepeated) {
    throw new Error(`${name} is listed twice`);
  }

  glyphs.set(name, Number.parseInt(code, HEXADECIMAL));
}

function keyOf(name: string) {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

const lines = [...glyphs].sort(([first], [second]) => first.localeCompare(second)).map(
  ([name, code]) => `  ${keyOf(name)}: 0x${code.toString(HEXADECIMAL).toUpperCase()}`
);

writeFileSync(
  OUTPUT_PATH,
  `// Generated by scripts/codegen/fetch-glyphs.ts from Microsoft's Segoe Fluent Icons list
// (MicrosoftDocs/windows-dev-docs at
// ${SOURCE_COMMIT},
// CC BY 4.0, credited in NOTICE). Do not edit.

/**
 * The code point of each icon of Segoe Fluent Icons, by the name Microsoft gives it, for a FontIcon's
 * \`glyph\`: \`FluentGlyph.Save\` is \`0xE74E\`.
 */
export const FluentGlyph = {
${lines.join(",\n")}
} as const;

/** The name of an icon of Segoe Fluent Icons. */
export type FluentGlyphName = keyof typeof FluentGlyph;

/** The code point of an icon of Segoe Fluent Icons: the only numbers a \`glyph\` takes. */
export type FluentGlyphCode = (typeof FluentGlyph)[FluentGlyphName];
`
);
console.log(`${glyphs.size} glyphs`);
