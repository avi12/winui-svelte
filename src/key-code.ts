/** The virtual-key code of one of `KeyCode`'s keys. */
export type KeyCode = typeof KeyCode[keyof typeof KeyCode];
/** The name of one of the keys, as `KeyCode` spells it. */
export type KeyCodeName = keyof typeof KeyCode;

/**
 * The web's `KeyboardEvent.code` of a key.
 *
 * @param name - The key, as `KeyCode` spells it.
 * @returns The name with its first letter in upper case (`keyA`, `KeyA`).
 */
export function webCodeOf(name: string) {
  return `${name.charAt(0).toUpperCase()}${name.slice(1)}`;
}
